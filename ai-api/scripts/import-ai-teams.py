#!/usr/bin/env python3
"""
what:    Build scripts/ai-teams.yaml from the competition website's allocation export
owner:   AIC
usage:   python ai-api/scripts/import-ai-teams.py <export-dir>/allocation.csv [--out scripts/ai-teams.yaml] [--dry-run]
         (the website writes allocation.csv with:  python manage.py export_range --competition <id> --out <dir>)
reads:   allocation.csv (columns enterprise, cell_id, namespace, kind, side, track, team_identifier, team_name)
changes: writes --out (or prints it with --dry-run). Team names are NOT copied: the AI VM needs identifiers only.
safe to run again: yes — same export gives the same file
rules:   AI Blue = side blue + track ai, numbered AI-01… by (cell_id, enterprise); WireGuard 10.62.<n>.0/24
         AI Red  = side red + track ai,  numbered RI-01… the same way;            WireGuard 10.64.<n>.0/24
         Pairing (Architecture §3.2, two AI Red per AI Blue): RI-01, RI-02 -> AI-01; RI-03, RI-04 -> AI-02; …
         Edit `paired` by hand afterwards if the organisers pair differently; re-importing resets it.
"""
import argparse
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = """# The AI track teams (Competition Architecture §3, §5.2, §15). AI teams are not cells.
# GENERATED by ai-api/scripts/import-ai-teams.py from the website's allocation export ({source}).
# Do not edit by hand except `paired`; re-run the import after allocation changes.
#   code      short name in the AI API and its logs   team_id   the website's identifier (= telemetry actor.team_id)
#   role      ai-blue reads everything / ai-red reads only its own traffic   wg_range  address plan /24
#   paired    ai-red only: the AI Blue team it tries to make wrong          enabled   false = no token works
teams:
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("allocation_csv")
    ap.add_argument("--out", default=str(ROOT / "scripts/ai-teams.yaml"))
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    with open(a.allocation_csv, encoding="utf-8", newline="") as fh:
        rows = [r for r in csv.DictReader(fh) if (r.get("track") or "").strip().lower() == "ai"]
    blue = sorted((r for r in rows if r["side"].strip().lower() == "blue"), key=lambda r: (r["cell_id"], r["enterprise"]))
    red = sorted((r for r in rows if r["side"].strip().lower() == "red"), key=lambda r: (r["cell_id"], r["enterprise"]))
    missing = [r["cell_id"] or "?" for r in blue + red if not r.get("team_identifier", "").strip()]
    if missing:
        print(f"refusing: AI teams without a team_identifier in the export: {missing}", file=sys.stderr)
        return 1
    if len(blue) > 9 or len(red) > 9:
        print("refusing: more than 9 AI Blue or AI Red teams does not fit the AI-0n / RI-0n codes", file=sys.stderr)
        return 1

    lines = []
    for n, r in enumerate(blue, 1):
        lines.append(f"  - {{ code: AI-{n:02d}, team_id: {r['team_identifier'].strip()}, role: ai-blue, "
                     f"wg_range: 10.62.{n}.0/24, enabled: true }}")
    for n, r in enumerate(red, 1):
        paired = f"AI-{(n + 1) // 2:02d}" if blue else ""
        if blue and (n + 1) // 2 > len(blue):
            paired = f"AI-{((n - 1) % len(blue)) + 1:02d}"
        lines.append(f"  - {{ code: RI-{n:02d}, team_id: {r['team_identifier'].strip()}, role: ai-red, "
                     f"wg_range: 10.64.{n}.0/24, paired: {paired}, enabled: true }}")
    text = HEADER.format(source=pathlib.Path(a.allocation_csv).name) + "\n".join(lines) + "\n"
    if a.dry_run:
        print(text, end="")
    else:
        pathlib.Path(a.out).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {len(blue)} AI Blue and {len(red)} AI Red teams to {a.out}")
        print("next: re-issue tokens for new teams (issue-tokens.py --team <code>) and restart the AI API")
    if not blue or not red:
        print("warning: the export has no AI Blue or no AI Red teams", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
