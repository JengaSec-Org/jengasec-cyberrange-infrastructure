#!/usr/bin/env python3
"""
what:    Issue one bearer token per enabled AI team; store only their hashes
owner:   AIC
usage:   python ai-api/scripts/issue-tokens.py [--out ai-api/tokens.yaml] [--team AI-01 ...] [--print-to FILE]
reads:   scripts/ai-teams.yaml
changes: writes --out (hashes only, never commit it). Each new token is printed ONCE (or written to
         --print-to, mode 600): publish it on that team's page on the website, never in chat.
         Lost token = run again with --team <code>; the old one stops working.
safe to run again: yes — re-issuing replaces the old token for the teams you name (or all of them)
"""
import argparse
import hashlib
import os
import pathlib
import secrets

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--teams", default=str(ROOT / "scripts/ai-teams.yaml"))
    ap.add_argument("--out", default=str(ROOT / "ai-api/tokens.yaml"))
    ap.add_argument("--team", action="append", help="only (re)issue for this team code; repeatable")
    ap.add_argument("--print-to", help="write the plain tokens to this file (mode 600) instead of the screen")
    a = ap.parse_args()

    teams = [t for t in yaml.safe_load(pathlib.Path(a.teams).read_text(encoding="utf-8"))["teams"] if t.get("enabled")]
    wanted = set(a.team or [t["code"] for t in teams])
    unknown = wanted - {t["code"] for t in teams}
    if unknown:
        raise SystemExit(f"not an enabled AI team: {', '.join(sorted(unknown))}")

    out = pathlib.Path(a.out)
    current = (yaml.safe_load(out.read_text(encoding="utf-8")) or {}).get("tokens", {}) if out.exists() else {}
    lines = [f"{'team':<6} {'role':<8} token (shown once)"]
    for t in teams:
        if t["code"] in wanted:
            token = f"jsai_{t['code'].lower().replace('-', '')}_{secrets.token_urlsafe(24)}"
            current[t["code"]] = hashlib.sha256(token.encode()).hexdigest()
            lines.append(f"{t['code']:<6} {t['role']:<8} {token}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# SHA-256 of each AI team token. Generated by issue-tokens.py. Never commit.\n"
                   + yaml.safe_dump({"tokens": dict(sorted(current.items()))}), encoding="utf-8", newline="\n")
    if a.print_to:
        fd = os.open(a.print_to, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(lines) + "\n")
        print(f"wrote {len(lines) - 1} tokens to {a.print_to} (mode 600)")
    else:
        print("\n".join(lines))
    print(f"wrote {len(current)} hashes to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
